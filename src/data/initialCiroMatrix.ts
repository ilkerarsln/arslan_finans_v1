export function mapSaleToCiroRow(sale: {
  brand?: string;
  altKategori?: string;
  subCategory?: string;
  category?: string;
  anaKategori?: string;
  productName?: string;
}): string {
  const parts = [
    sale.brand || '',
    sale.altKategori || '',
    sale.subCategory || '',
    sale.productName || '',
    sale.category || '',
    sale.anaKategori || '',
  ]
    .join(' ')
    .toUpperCase();

  // 1. Doğrudan Marka & Alt Kategori Kontrolü
  if (parts.includes('ALTUS')) return 'ALTUS';
  if (parts.includes('UGUR') || parts.includes('UĞUR')) return 'UGUR';
  if (parts.includes('HOOVER')) return 'HOOVER';
  if (parts.includes('KEA') || parts.includes('TEFAL') || parts.includes('KARCHER')) return 'KEA';
  if (parts.includes('BOSCH')) return 'BOSCH';
  if (parts.includes('TV') || parts.includes('SKYTECH') || parts.includes('TELEVİZYON')) return 'TV';
  if (parts.includes('BAMBI') || parts.includes('BAMBİ')) return 'BAMBI';
  if (parts.includes('MEDISA') || parts.includes('MEDİSA')) return 'MEDISA';
  if (parts.includes('MASA') || parts.includes('SANDALYE') || parts.includes('BULUT')) return 'MASA';
  if (parts.includes('AKSESUAR') || parts.includes('SEHPA') || parts.includes('BÜRO') || parts.includes('DEKORASYON')) return 'AKSESUAR';
  if (parts.includes('YATAK') || parts.includes('BEDLIFE') || parts.includes('FİENTO')) return 'YATAK';

  // 2. Ana Kategori bazlı fallback
  const ana = (sale.anaKategori || sale.category || '').toUpperCase();
  if (ana.includes('BEYAZ')) return 'ALTUS';
  return 'MOBILYA';
}

